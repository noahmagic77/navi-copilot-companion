'use strict';
const fs=require('node:fs');
const path=require('node:path');
const {motions,idleMotionIds,greetingMotionIds,createGreetingSelector,sampleMotion}=require('../media/fairy-motion.js');
const samples=motions.flatMap(m=>[0,.15,.37,.5,.85,1].map(fraction=>({id:m.id,age:m.duration*fraction,elapsed:2,pose:Object.values(sampleMotion(m.id,m.duration*fraction,2))})));
const target=path.join(__dirname,'../native/overlay/internal/motion/testdata/poses.json');
const data=JSON.stringify(samples,null,2)+'\n';
if(process.argv.includes('--check')){
 const expected=JSON.parse(fs.readFileSync(target,'utf8'));
 function equal(a,b){if(typeof a==='number'&&typeof b==='number')return Math.abs(a-b)<1e-9;if(Array.isArray(a)&&Array.isArray(b))return a.length===b.length&&a.every((v,i)=>equal(v,b[i]));if(a&&b&&typeof a==='object'&&typeof b==='object')return Object.keys(a).length===Object.keys(b).length&&Object.keys(a).every(key=>equal(a[key],b[key]));return a===b;}
 if(!equal(expected,samples))throw Error('Native motion fixture differs from the webview motion catalogue');
}else{fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,data);}

// The browser catalogue is the source of truth for host validation and native
// definitions. Check these generated sources along with the parity fixture.
const extra=motions.filter(m=>m.profile);
const go='// Code generated by scripts/native-motion-fixture.cjs; DO NOT EDIT.\npackage motion\n\n'+
 'var extendedDefinitions = []Definition{\n'+extra.map(m=>`\t{ID: ${JSON.stringify(m.id)}, Duration: ${m.duration}},`).join('\n')+'\n}\n\n'+
 'var patterns = map[string]pattern{\n'+extra.map(m=>`\t${JSON.stringify(m.id)}: {Kind: ${m.profile.kind}, AX: ${m.profile.ax}, AY: ${m.profile.ay}, Cycles: ${m.profile.cycles}, Phase: ${m.profile.phase}, Tilt: ${m.profile.tilt}},`).join('\n')+'\n}\n\n'+
 'var IdleMotions = []string{'+idleMotionIds.map(id=>JSON.stringify(id)).join(', ')+'}\n'+
 'var GreetingMotions = []string{'+greetingMotionIds.map(id=>JSON.stringify(id)).join(', ')+'}\n';
const ts='// Generated by scripts/native-motion-fixture.cjs; do not edit.\n'+
 'export const motionCatalog = '+JSON.stringify(motions.map(({id,label,category,duration})=>({id,label,category,duration})),null,2)+' as const;\n'+
 'export const motionIds: ReadonlySet<string> = new Set(motionCatalog.map(motion => motion.id));\n'+
 'export const greetingMotionIds: readonly string[] = '+JSON.stringify(greetingMotionIds)+';\n'+
 'export const createGreetingSelector = '+createGreetingSelector.toString().replace(/\r\n/g,'\n').replace('previous = bag.pop();','previous = bag.pop()!;')+';\n';
for(const [file,contents] of [['native/overlay/internal/motion/catalog_generated.go',go],['src/core/motionCatalog.ts',ts]]){
 const location=path.join(__dirname,'..',file);
 if(process.argv.includes('--check')){
  if(fs.readFileSync(location,'utf8').replace(/\r\n/g,'\n')!==contents)throw Error('Generated motion catalogue is stale: '+file);
 }else fs.writeFileSync(location,contents);
}
